#!/usr/bin/env node
// Keeps the Rust quit wait equal to the TS shutdown waits. Run after changing constants.ts.
import { readFileSync, writeFileSync } from 'node:fs'

const TARGET = new URL('../src-tauri/src/server/shutdown_waits.rs', import.meta.url)
const constants = await import(new URL('../src/core/constants.ts', import.meta.url).href)

const image = constants.SHUTDOWN_IMAGE_WAIT_MS
const download = constants.SHUTDOWN_DOWNLOAD_WAIT_MS
const work = Math.max(image, download)

const text = `// Generated by scripts/shutdown-waits.mjs from src/core/constants.ts.
#[cfg(test)]
pub(crate) const IMAGE_WAIT_MS: u64 = ${String(image)};
#[cfg(test)]
pub(crate) const DOWNLOAD_WAIT_MS: u64 = ${String(download)};
pub(crate) const WORK_WAIT_MS: u64 = ${String(work)};
`

if (process.argv.includes('--check')) {
  const current = readFileSync(TARGET, 'utf8')
  if (current !== text) {
    console.error('[shutdown-waits] src-tauri/src/server/shutdown_waits.rs is stale')
    process.exit(1)
  }
  console.log('[shutdown-waits] Rust waits match src/core/constants.ts')
} else {
  writeFileSync(TARGET, text)
  console.log('[shutdown-waits] wrote src-tauri/src/server/shutdown_waits.rs')
}
