import fs from 'node:fs/promises'
import path from 'node:path'

import { isString } from 'lodash-es'
import { describe, expect, it } from 'vitest'
import { z } from 'zod'

import { isNonEmptyString } from '../src/core/guards'

const ROOT = process.cwd()
const TAURI = path.join(ROOT, 'src-tauri')
const SRC = path.join(TAURI, 'src')
const AUTOGENERATED = path.join(TAURI, 'permissions', 'autogenerated')
const LOCAL_CAPABILITY = path.join(TAURI, 'capabilities', 'default.json')
const REMOTE_CAPABILITY = path.join(TAURI, 'capability-remote.json')
const DESKTOP = path.join(ROOT, 'src', 'lib', 'platform', 'desktop.ts')
const SECURITY_DOC = path.join(ROOT, 'docs', 'SECURITY.md')

const COMMAND_ATTRIBUTE = /#\[tauri::command[^\]]*\][\s\S]{0,120}?fn\s+(\w+)/g
const HANDLER_LIST = /generate_handler!\[([\s\S]*?)\]/g
const MANIFEST_LIST = /commands\(&\[([\s\S]*?)\]\)/g
const INVOKE_CALL = /invoke(?:Checked)?(?:<[^>]*>)?\(\s*'([a-z0-9_]+)'/g
const QUOTED_COMMAND = /"([a-z0-9_]+)"/g
const ALLOW_IDENTIFIER = /identifier\s*=\s*"allow-([a-z0-9-]+)"/g

const AllowRuleSchema = z.object({ url: z.string().optional(), path: z.string().optional() })

const PermissionSchema = z.union([
  z.string(),
  z.object({ identifier: z.string(), allow: z.array(AllowRuleSchema).optional() }),
])

const CapabilitySchema = z.object({ permissions: z.array(PermissionSchema) })

type CapabilityPermission = z.infer<typeof PermissionSchema>

interface Capability {
  permissions: CapabilityPermission[]
}

interface Contract {
  declared: string[]
  handlers: string[]
  manifest: string[]
  permissions: string[]
  invoked: string[]
  local: Capability
  remote: Capability
  localAppPermissions: string[]
  remoteAppPermissions: string[]
  expectedAllow: string[]
}

let cached: Promise<Contract> | null = null

async function read(file: string): Promise<string> {
  return fs.readFile(file, 'utf8')
}

async function listRustFiles(dir: string): Promise<string[]> {
  const entries = await fs.readdir(dir, { withFileTypes: true })

  const nested = await Promise.all(
    entries.map((entry) => {
      const full = path.join(dir, entry.name)

      if (entry.isDirectory()) {
        return listRustFiles(full)
      }

      return Promise.resolve(entry.name.endsWith('.rs') ? [full] : [])
    }),
  )

  return nested.flat()
}

function collected(source: string, pattern: RegExp): string[] {
  const found = Array.from(source.matchAll(pattern)).map((match) => {
    return match[1] ?? ''
  })

  return found.filter(isNonEmptyString)
}

function lastSegment(entry: string): string {
  const parts = entry.trim().split('::')

  return parts.at(-1) ?? ''
}

function allowIdentifier(command: string): string {
  return `allow-${command.replaceAll('_', '-')}`
}

function permissionNames(permissions: CapabilityPermission[]): string[] {
  return permissions.map((permission) => {
    return isString(permission) ? permission : permission.identifier
  })
}

function isAppPermission(name: string): boolean {
  return name.startsWith('allow-')
}

async function loadCapability(file: string): Promise<Capability> {
  return CapabilitySchema.parse(JSON.parse(await read(file)))
}

async function buildContract(): Promise<Contract> {
  const files = await listRustFiles(SRC)
  const rust = (await Promise.all(files.map(read))).join('\n')

  const declared = collected(rust, COMMAND_ATTRIBUTE).sort()

  const handlers = collected(rust, HANDLER_LIST)
    .join(',')
    .split(',')
    .map(lastSegment)
    .filter(isNonEmptyString)
    .sort()

  const build = await read(path.join(TAURI, 'build.rs'))
  const manifest = collected(collected(build, MANIFEST_LIST).join(','), QUOTED_COMMAND).sort()

  const tomlNames = (await fs.readdir(AUTOGENERATED)).filter((name) => {
    return name.endsWith('.toml')
  })

  const toml = await Promise.all(
    tomlNames.map((name) => {
      return read(path.join(AUTOGENERATED, name))
    }),
  )

  const permissions = collected(toml.join('\n'), ALLOW_IDENTIFIER).map(allowIdentifier).sort()

  const invoked = Array.from(new Set(collected(await read(DESKTOP), INVOKE_CALL))).sort()

  const local = await loadCapability(LOCAL_CAPABILITY)
  const remote = await loadCapability(REMOTE_CAPABILITY)
  const expectedAllow = manifest.map(allowIdentifier).sort()

  const localAppPermissions = permissionNames(local.permissions).filter(isAppPermission).sort()
  const remoteAppPermissions = permissionNames(remote.permissions).filter(isAppPermission).sort()

  return {
    declared,
    handlers,
    manifest,
    permissions,
    invoked,
    local,
    remote,
    localAppPermissions,
    remoteAppPermissions,
    expectedAllow,
  }
}

function contract(): Promise<Contract> {
  cached ??= buildContract()

  return cached
}

describe('desktop command contract', () => {
  it('marks the same commands in Rust as the handler list registers', async () => {
    const result = await contract()

    expect(result.declared).toEqual(result.handlers)
  })

  it('lists the handler set in the app manifest', async () => {
    const result = await contract()

    expect(result.manifest).toEqual(result.handlers)
  })

  it('generates one permission file per manifest command', async () => {
    const result = await contract()

    expect(result.permissions).toEqual(result.expectedAllow)
  })

  it('grants the manifest commands in both capabilities', async () => {
    const result = await contract()

    expect(result.localAppPermissions).toEqual(result.expectedAllow)
    expect(result.remoteAppPermissions).toEqual(result.expectedAllow)
  })

  it('keeps the local and remote capabilities identical', async () => {
    const result = await contract()

    expect(result.remote.permissions).toEqual(result.local.permissions)
  })

  it('invokes exactly the manifest commands from the desktop module', async () => {
    const result = await contract()

    expect(result.invoked).toEqual(result.manifest)
  })

  it('names every manifest command in the security doc', async () => {
    const result = await contract()
    const doc = await read(SECURITY_DOC)

    const missing = result.manifest.filter((command) => {
      return !doc.includes(`\`${command}\``)
    })

    expect(missing).toEqual([])
  })

  it('uses the mp4 filter for the video save dialog only', async () => {
    const exportSource = await read(path.join(SRC, 'export.rs'))
    const desktop = await read(DESKTOP)

    expect(exportSource).toContain('add_filter("Video", &["mp4"])')
    expect(desktop).toContain('`${promptSlug(record)}.mp4`')
    expect(Array.from(desktop.matchAll(/choose_export_path/g))).toHaveLength(1)
  })
})
